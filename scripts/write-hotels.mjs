const errors = [];
for (const r of ROWS) {
  for (const [field, allowed] of Object.entries(VOCAB)) {
    const v = String(r[field] ?? "");
    if (v === "") continue;
    for (const part of v.split(",").map((x) => x.trim()).filter(Boolean))
      if (!allowed.includes(part))
        errors.push(`${r.slug}: ${field} = "${part}" is not in [${allowed.filter(Boolean).join(", ")}]`);
  }
  if (r.hood && !HOODS[r.hood]) errors.push(`${r.slug}: neighbourhood "${r.hood}" is not in HOODS`);
  // A row with no brand cannot be routed to a programme by the affiliate
  // resolver, so it would silently fall through to the aggregator forever.
  if (!r.brand) errors.push(`${r.slug}: has no Brand - the affiliate resolver keys on it`);
}
if (errors.length) {
  console.error(`${errors.length} error(s):`);
  for (const e of errors) console.error("  " + e);
  process.exit(1);
}
